import type { ReactNode } from "react";
import { failureReasonsByLevel, levelTotals, returners, segmentRevenue, summary } from "@/lib/server-metrics";
import { fmtInt, fmtPct } from "@/lib/format";
import { Pill, Section, SectionHeading, SyntheticNote } from "./ui";

function Step({ n, title, tag, children }: { n: number; title: string; tag?: ReactNode; children: ReactNode }) {
  return (
    <li className="relative pl-10">
      <span className="absolute left-0 top-0 grid h-7 w-7 place-items-center rounded-full border border-accent/40 bg-ink-900 font-mono text-xs text-accent">{n}</span>
      <div className="flex flex-wrap items-center gap-2">
        <h3 className="text-base font-semibold text-fg">{title}</h3>
        {tag}
      </div>
      <div className="mt-2 space-y-3 text-sm leading-relaxed text-fg-2">{children}</div>
    </li>
  );
}

const REASON_LABEL: Record<string, string> = {
  Enemy_Damage: "Enemy damage",
  Time_Expired: "Time expired",
  Boss_Fight: "Boss fight",
  Insufficient_Health: "Insufficient health",
  Player_Abandoned: "Player abandoned",
};

export default function CaseStudy() {
  const worst = [...levelTotals].sort((a, b) => b.failRate - a.failRate)[0];
  const others = levelTotals.filter((l) => l.level !== worst.level);
  const othersRate = others.reduce((a, l) => a + l.failed, 0) / others.reduce((a, l) => a + l.started, 0);

  const reasonShare = (lvl: number | "others") => {
    const acc: Record<string, number> = {};
    for (const [k, v] of Object.entries(failureReasonsByLevel)) {
      if (lvl === "others" ? Number(k) === worst.level : Number(k) !== lvl) continue;
      for (const [r, c] of Object.entries(v)) acc[r] = (acc[r] ?? 0) + c;
    }
    const t = Object.values(acc).reduce((a, b) => a + b, 0);
    return Object.fromEntries(Object.entries(acc).map(([r, c]) => [r, c / t]));
  };
  const worstMix = reasonShare(worst.level);
  const otherMix = reasonShare("others");

  const hs = segmentRevenue.find((s) => s.segment === "High Spender");
  const r = returners.retainedD7;
  const c = returners.notRetainedD7;

  return (
    <Section id="case-study">
      <SectionHeading
        kicker="Case study"
        title="From a business question to a validated recommendation"
        intro={
          <p>
            How I&apos;d work through a game-analytics problem, using GAMEPULSE as the dataset. Findings marked{" "}
            <Pill tone="accent">GAMEPULSE data</Pill> are computed from the synthetic dataset; anything marked <Pill tone="warn">Hypothetical</Pill> is an illustrative scenario.
          </p>
        }
      />
      <div className="mb-8">
        <SyntheticNote>
          GAMEPULSE data is generated by a script, so patterns like the level spike below may have been designed into the generator. The value here is the method — how a spike is found, explained and validated — not the number itself.
        </SyntheticNote>
      </div>

      <ol className="space-y-10 border-l border-line pl-0 [&>li]:ml-[-14px]">
        <Step n={1} title="Business question">
          <p className="text-fg">“Is any level blocking progression — and are the players who leave different from the players who stay?”</p>
          <p>A good question names the decision it supports: here, whether to re-tune a level or change onboarding, and how to prove the change worked.</p>
        </Step>

        <Step n={2} title="Data & event model" tag={<Pill tone="accent">GAMEPULSE data</Pill>}>
          <p>
            GAMEPULSE stores one row per event in <code className="font-mono text-fg">raw_game_events</code> with columns{" "}
            <code className="font-mono text-fg">event_id, player_id, event_name, event_timestamp, session_id, platform, country, game_version, event_properties</code>{" "}
            (JSON), plus a <code className="font-mono text-fg">players</code> table with registration date, platform, country, acquisition channel and segment.
          </p>
          <p>
            {summary.eventTypes} event types cover the lifecycle: <code className="font-mono text-fg-2">player_registered → tutorial → session_started → match/level → purchase_completed → session_ended</code>. Level number, failure reason and price live inside <code className="font-mono">event_properties</code>.
          </p>
        </Step>

        <Step n={3} title="Data quality">
          <p>
            Before any metric: unique <code className="font-mono">event_id</code>, no events for unknown players, timestamps inside the analysis window, session end after start, valid JSON properties. GAMEPULSE&apos;s validation script runs these checks, and the export behind this site re-asserts the key ones and fails rather than publishing bad numbers.
          </p>
        </Step>

        <Step n={4} title="SQL analysis">
          <p>
            Level failure rate per level, D1/D7 retention per registration cohort, and a returner-vs-churner comparison. The exact query patterns are in the SQL showcase below — each one states its time window and denominator.
          </p>
        </Step>

        <Step n={5} title="KPI definitions">
          <ul className="grid gap-2 sm:grid-cols-2">
            <li className="card p-3"><b className="text-fg">Level failure rate</b> = level_failed ÷ level_started for that level.</li>
            <li className="card p-3"><b className="text-fg">D7 retention</b> = cohort players with a session on registration date + 7 ÷ cohort size.</li>
            <li className="card p-3"><b className="text-fg">Payer conversion</b> = distinct paying players ÷ registered players (Sep 2026).</li>
            <li className="card p-3"><b className="text-fg">ARPPU</b> = revenue ÷ distinct paying players, same period.</li>
          </ul>
        </Step>

        <Step n={6} title="Findings" tag={<Pill tone="accent">GAMEPULSE data</Pill>}>
          <div className="grid gap-3 lg:grid-cols-3">
            <div className="card p-4">
              <p className="font-mono text-2xl text-fg">{fmtPct(worst.failRate)}</p>
              <p className="mt-1 text-fg">Level {worst.level} failure rate</p>
              <p className="mt-2 text-xs">
                vs {fmtPct(othersRate)} across all other levels ({fmtInt(worst.failed)} failures in {fmtInt(worst.started)} attempts). At level {worst.level},{" "}
                {fmtPct(worstMix.Player_Abandoned ?? 0, 0)} of failures are abandonment vs {fmtPct(otherMix.Player_Abandoned ?? 0, 0)} elsewhere — players keep fighting and lose to{" "}
                {Object.entries(worstMix)
                  .filter(([k]) => k !== "Player_Abandoned")
                  .sort((a, b) => b[1] - a[1])
                  .slice(0, 2)
                  .map(([k, v]) => `${REASON_LABEL[k] ?? k} (${fmtPct(v, 0)})`)
                  .join(" and ")}
                . That points to a broad difficulty spike, not one broken mechanic.
              </p>
            </div>
            <div className="card p-4">
              <p className="font-mono text-2xl text-fg">
                {fmtPct(r.activeDaysFirst3 / Math.max(c.activeDaysFirst3, 0.0001) - 1, 0)}
              </p>
              <p className="mt-1 text-fg">more early activity among D7 returners</p>
              <p className="mt-2 text-xs">
                Players still active on day 7 averaged {r.activeDaysFirst3.toFixed(2)} active days in their first three days vs {c.activeDaysFirst3.toFixed(2)} for those who weren&apos;t. Tutorial completion: {fmtPct(r.tutorialCompletion)} vs {fmtPct(c.tutorialCompletion)}. Payer rate: {fmtPct(r.payerRate)} vs {fmtPct(c.payerRate)} — but returners also had more days in which to buy, so this is association, not cause.
              </p>
            </div>
            {hs ? (
              <div className="card p-4">
                <p className="font-mono text-2xl text-fg">{fmtPct(hs.share, 0)}</p>
                <p className="mt-1 text-fg">of revenue from High Spenders</p>
                <p className="mt-2 text-xs">
                  The High Spender segment is under 5% of players but generates {fmtPct(hs.share, 0)} of revenue. That concentration is a risk: any change that alienates this group has an outsized effect, so it needs its own guardrail metric.
                </p>
              </div>
            ) : null}
          </div>
        </Step>

        <Step n={7} title="Recommendations" tag={<Pill tone="warn">Hypothetical</Pill>}>
          <ul className="list-disc space-y-1.5 pl-5">
            <li>Re-tune level {worst.level} (enemy damage, timer or health pickups) or add a mid-level checkpoint — aiming for the ~{fmtPct(othersRate, 0)} failure rate seen elsewhere, not zero.</li>
            <li>Nudge new players toward a second session in their first three days (daily reward reminder, short first-session goal), since early activity is the clearest difference between returners and churners.</li>
            <li>Track High Spender retention as a guardrail for any monetization change.</li>
          </ul>
        </Step>

        <Step n={8} title="Validation plan" tag={<Pill tone="warn">Hypothetical</Pill>}>
          <p>
            Correlation is not causation. Ship the level change as an A/B test: random 50/50 split of players reaching level {worst.level - 1}, primary metric = level {worst.level} completion within the session, guardrails = D7 retention, session length and revenue per player. Fix the sample size and test length before starting, and don&apos;t stop early when the chart looks good.
          </p>
        </Step>

        <Step n={9} title="Limitations">
          <ul className="list-disc space-y-1.5 pl-5">
            <li>Synthetic data: patterns reflect the generator&apos;s design, not real players.</li>
            <li>One month and one game version ({Object.keys(summary.eventCounts).length} event types, version 1.0.0 only) — no seasonality and no before/after-update comparison is possible.</li>
            <li>D14 retention only covers players registered by 16 Sep.</li>
          </ul>
        </Step>
      </ol>

      {/* Scenario playbooks */}
      <div className="mt-14 grid gap-4 md:grid-cols-3">
        {[
          {
            t: "Investigating a high level-failure rate",
            steps: [
              "Confirm it's real: check event volume, duplicates and logging changes for that level.",
              "Split by platform, segment and attempt number — is it everyone or one group?",
              "Break failures down by cause (damage, timer, abandon).",
              "Compare with neighbouring levels and with time-to-fail.",
              "Recommend a tuning change and A/B test it.",
            ],
          },
          {
            t: "Comparing returners with churners",
            steps: [
              "Define churn explicitly (e.g. no session on day 7) and fix the cohort window.",
              "Compare first-session and first-3-day behaviour: sessions, tutorial, levels reached.",
              "Only compare behaviour before the churn point, to avoid survivorship bias.",
              "Treat differences as hypotheses, then test interventions.",
            ],
          },
          {
            t: "Retention dropped after a game update",
            steps: [
              "Line up cohorts by install date and game_version; compare D1/D7 before vs after.",
              "Rule out mix shifts: new acquisition channel, platform, country.",
              "Check instrumentation — did an event change or stop firing?",
              "Diff funnels (tutorial, level 1–5) between versions to locate the drop.",
              "Roll back or fix behind a flag, and measure with a holdout.",
            ],
          },
        ].map((s) => (
          <div key={s.t} className="card p-5">
            <div className="flex items-start justify-between gap-2">
              <h3 className="text-sm font-semibold text-fg">{s.t}</h3>
            </div>
            <Pill tone="warn">Hypothetical playbook</Pill>
            <ol className="mt-3 list-decimal space-y-1.5 pl-5 text-sm text-fg-2">
              {s.steps.map((x) => (
                <li key={x}>{x}</li>
              ))}
            </ol>
          </div>
        ))}
      </div>
    </Section>
  );
}
