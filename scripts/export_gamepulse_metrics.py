"""
Export verified GAMEPULSE metrics to a static JSON file for the portfolio dashboard.

Source data: the raw CSVs from https://github.com/Shannuvenu/GAMEPULSE
(data/raw/players.csv and data/raw/game_events.csv, stored with Git LFS).

Usage:
    python scripts/export_gamepulse_metrics.py <path-to-GAMEPULSE/data/raw> [output.json]

Default output: public/data/gamepulse-metrics.json

Metric definitions (also shown on the site):
- DAU: distinct players with >= 1 `session_started` event on that calendar day.
- Sessions: count of `session_started` events.
- Match completion rate: match_completed / match_started.
- Revenue: sum of `price` on `purchase_completed` events with payment_status = SUCCESS (INR).
- Payer conversion: distinct paying players / all registered players.
- ARPU: revenue / all registered players (September 2026).
- ARPPU: revenue / distinct paying players (September 2026).
- Day-N retention: share of a registration cohort with a `session_started` exactly N
  calendar days after registration_date. A cohort only counts toward Day-N if
  registration_date + N <= last day of data (2026-09-30).
All numbers come from synthetic data generated by the GAMEPULSE project.
"""

import json
import sys
from pathlib import Path

import pandas as pd

RAW = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("data/raw")
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "public/data/gamepulse-metrics.json"
RET_DAYS = [1, 3, 7, 14]

players = pd.read_csv(RAW / "players.csv", parse_dates=["registration_date"])
ev = pd.read_csv(
    RAW / "game_events.csv",
    usecols=["event_id", "player_id", "event_name", "event_timestamp", "session_id", "platform", "event_properties"],
    parse_dates=["event_timestamp"],
)
ev["date"] = ev["event_timestamp"].dt.normalize()
last_day = ev["date"].max()

# --- Data quality checks (fail loudly rather than export bad numbers) ---
assert ev["event_id"].is_unique, "duplicate event_id"
assert players["player_id"].is_unique, "duplicate player_id"
assert ev["player_id"].isin(players["player_id"]).all(), "events reference unknown players"

seg = players.set_index("player_id")["player_segment"]
country = players.set_index("player_id")["country"]
plat = players.set_index("player_id")["platform"]


def props(name: str) -> pd.DataFrame:
    sub = ev[ev["event_name"] == name]
    p = pd.json_normalize(sub["event_properties"].map(json.loads).tolist())
    p.index = sub.index
    return sub.join(p)


sessions = ev[ev["event_name"] == "session_started"]
ses_end = props("session_ended")
purch = props("purchase_completed")
purch = purch[purch["payment_status"] == "SUCCESS"]
purch["segment"] = purch["player_id"].map(seg)
purch["country"] = purch["player_id"].map(country)
lvl = props("level_started"), props("level_completed"), props("level_failed")

def fmt(d):
    return d.strftime("%Y-%m-%d")

# --- Daily x platform rows (all additive across platforms) ---
keys = ["date", "platform"]
daily = (
    sessions.groupby(keys).agg(dau=("player_id", "nunique"), sessions=("event_id", "size"))
    .join(ev[ev.event_name == "match_started"].groupby(keys).size().rename("matchesStarted"))
    .join(ev[ev.event_name == "match_completed"].groupby(keys).size().rename("matchesCompleted"))
    .join(ev[ev.event_name == "player_registered"].groupby(keys).size().rename("newPlayers"))
    .join(purch.groupby(keys)["price"].sum().rename("revenue"))
    .join(purch.groupby(keys).size().rename("purchases"))
    .join(ses_end.groupby(keys)["session_duration_seconds"].sum().rename("sessionSeconds"))
    .fillna(0).reset_index()
)
daily["date"] = daily["date"].map(fmt)

# --- Retention cohorts by registration date x platform ---
active = sessions[["player_id", "date"]].drop_duplicates()
pl = players[["player_id", "registration_date", "platform"]]
act = active.merge(pl, on="player_id")
act["dayN"] = (act["date"] - act["registration_date"]).dt.days
cohorts = []
for (rd, pf), grp in pl.groupby(["registration_date", "platform"]):
    row = {"cohortDate": fmt(rd), "platform": pf, "size": int(len(grp))}
    ids = set(grp["player_id"])
    a = act[act["player_id"].isin(ids)]
    for n in RET_DAYS:
        if rd + pd.Timedelta(days=n) <= last_day:
            row[f"d{n}"] = int(a.loc[a["dayN"] == n, "player_id"].nunique())
        else:
            row[f"d{n}"] = None
    cohorts.append(row)

# --- Levels x day x platform ---
ls, lc, lf = lvl
lv = (
    ls.groupby(["date", "platform", "level"]).size().rename("started").to_frame()
    .join(lc.groupby(["date", "platform", "level"]).size().rename("completed"))
    .join(lf.groupby(["date", "platform", "level"]).size().rename("failed"))
    .fillna(0).reset_index()
)
lv["date"] = lv["date"].map(fmt)
fail_reasons = lf["failure_reason"].value_counts().to_dict()
fail_by_level = {int(k): v for k, v in lf.groupby("level")["failure_reason"].value_counts().unstack(fill_value=0).to_dict("index").items()}

# --- Revenue by segment / country x day x platform ---
rev_seg = purch.groupby(["date", "platform", "segment"])["price"].sum().reset_index()
rev_seg["date"] = rev_seg["date"].map(fmt)
rev_cty = purch.groupby(["date", "platform", "country"])["price"].sum().reset_index()
rev_cty["date"] = rev_cty["date"].map(fmt)
products = purch.groupby("product_name").agg(price=("price", "first"), purchases=("price", "size"), revenue=("price", "sum")).reset_index()

# --- Headline summary ---
revenue = float(purch["price"].sum())
payers = purch["player_id"].nunique()
n_players = len(players)
ms = (ev.event_name == "match_started").sum()
mc = (ev.event_name == "match_completed").sum()
ma = (ev.event_name == "match_abandoned").sum()
coh = pd.DataFrame(cohorts)
ret = {f"d{n}": float(coh[f"d{n}"].dropna().sum() / coh.loc[coh[f"d{n}"].notna(), "size"].sum()) for n in RET_DAYS}
tut_s = (ev.event_name == "tutorial_started").sum()
tut_c = (ev.event_name == "tutorial_completed").sum()

# Returners vs churners: compare D7-eligible players retained on D7 vs not
elig = pl[pl["registration_date"] + pd.Timedelta(days=7) <= last_day]
d7_ids = set(act.loc[act["dayN"] == 7, "player_id"])
first3 = act[(act["dayN"] >= 0) & (act["dayN"] <= 2)].groupby("player_id").size()
tut_done = set(ev.loc[ev.event_name == "tutorial_completed", "player_id"])
payer_ids = set(purch["player_id"])
def cohort_profile(ids):
    ids = list(ids)
    return {
        "players": len(ids),
        "activeDaysFirst3": float(first3.reindex(ids).fillna(0).mean()),
        "tutorialCompletion": float(pd.Series(ids).isin(tut_done).mean()),
        "payerRate": float(pd.Series(ids).isin(payer_ids).mean()),
    }
ret_ids = [p for p in elig["player_id"] if p in d7_ids]
churn_ids = [p for p in elig["player_id"] if p not in d7_ids]

summary = {
    "period": {"start": fmt(ev["date"].min()), "end": fmt(last_day)},
    "players": n_players,
    "events": int(len(ev)),
    "eventTypes": int(ev["event_name"].nunique()),
    "sessions": int(len(sessions)),
    "avgSessionMinutes": float(ses_end["session_duration_seconds"].mean() / 60),
    "avgDau": float(daily.groupby("date")["dau"].sum().mean()),
    "matchesStarted": int(ms), "matchesCompleted": int(mc), "matchesAbandoned": int(ma),
    "matchCompletionRate": float(mc / ms),
    "levelAttempts": int(len(ls)), "levelCompleted": int(len(lc)), "levelFailed": int(len(lf)),
    "tutorialCompletionRate": float(tut_c / tut_s),
    "revenueInr": revenue, "purchases": int(len(purch)), "payingPlayers": int(payers),
    "payerConversion": float(payers / n_players),
    "arpuInr": revenue / n_players, "arppuInr": revenue / payers,
    "retention": ret,
    "eventCounts": ev["event_name"].value_counts().to_dict(),
}

out = {
    "source": "GAMEPULSE synthetic dataset (github.com/Shannuvenu/GAMEPULSE) — not live game telemetry",
    "summary": summary,
    "daily": daily.to_dict("records"),
    "cohorts": cohorts,
    "levels": lv.to_dict("records"),
    "failureReasons": fail_reasons,
    "failureReasonsByLevel": fail_by_level,
    "revenueBySegment": rev_seg.to_dict("records"),
    "revenueByCountry": rev_cty.to_dict("records"),
    "products": products.to_dict("records"),
    "returnersVsChurners": {"retainedD7": cohort_profile(ret_ids), "notRetainedD7": cohort_profile(churn_ids)},
}

def clean(o):
    if isinstance(o, dict):
        return {str(k): clean(v) for k, v in o.items()}
    if isinstance(o, list):
        return [clean(v) for v in o]
    if hasattr(o, "item"):
        o = o.item()
    if isinstance(o, float):
        return round(o, 4) if o == o else None
    return o

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps(clean(out), separators=(",", ":")))
print(f"Wrote {OUT} ({OUT.stat().st_size/1024:.0f} KB)")
print(json.dumps(clean(summary), indent=1))
print(json.dumps(clean(out["returnersVsChurners"]), indent=1))
